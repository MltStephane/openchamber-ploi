export const DICTIONARIES = { en: en as Dictionary, fr } as const;
export type Locale = keyof typeof DICTIONARIES;

export const resolveLocale = (tag: string | null | undefined): Locale => {
  const base = (tag ?? '').toLowerCase().split('-')[0] ?? '';
  return base in DICTIONARIES ? (base as Locale) : 'en';
};

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export const translator = (locale: Locale): Translate => (key, params = {}) => {
  const entry = DICTIONARIES[locale][key] as string | Plural;
  const count = Number(params.count ?? 0);
  const template = typeof entry === 'string' ? entry : new Intl.PluralRules(locale).select(count) === 'one' ? entry.one : entry.other;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
};
